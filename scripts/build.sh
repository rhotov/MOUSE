#!/bin/bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
CONFIGURATION="release"

case "${1:-}" in
    "") ;;
    --debug) CONFIGURATION="debug" ;;
    --help|-h)
        echo "Usage: ./scripts/build.sh [--debug]"
        echo "Build and ad-hoc sign dist/MOUSE.app for this Mac."
        exit 0
        ;;
    *) echo "Unknown option: $1" >&2; exit 2 ;;
esac
if [[ $# -gt 1 ]]; then
    echo "Usage: ./scripts/build.sh [--debug]" >&2
    exit 2
fi
if [[ "$(uname -s)" != "Darwin" ]]; then
    echo "MOUSE must be built on macOS with Apple's command line developer tools." >&2
    exit 1
fi

BUILD_DIR="$ROOT_DIR/.build"
mkdir -p "$BUILD_DIR/module-cache" "$BUILD_DIR/cache" "$BUILD_DIR/config" \
    "$BUILD_DIR/security" "$ROOT_DIR/dist"
export CLANG_MODULE_CACHE_PATH="$BUILD_DIR/module-cache"
export SWIFTPM_MODULECACHE_OVERRIDE="$BUILD_DIR/module-cache"

# Keep SwiftPM's writable state inside the project. Its nested sandbox is
# disabled so the same command also works from an already-sandboxed terminal.
BUILD_OPTIONS=(
    --package-path "$ROOT_DIR"
    --scratch-path "$BUILD_DIR"
    --cache-path "$BUILD_DIR/cache"
    --config-path "$BUILD_DIR/config"
    --security-path "$BUILD_DIR/security"
    --manifest-cache local
    --disable-sandbox
    --configuration "$CONFIGURATION"
    --product MOUSE
    -Xswiftc -module-cache-path -Xswiftc "$BUILD_DIR/module-cache"
)

# A local release bundle does not need a separate debug-symbol archive.
if [[ "$CONFIGURATION" == "release" ]]; then
    BUILD_OPTIONS+=(-debug-info-format none)
fi

xcrun swift build "${BUILD_OPTIONS[@]}"
BIN_DIR="$(xcrun swift build "${BUILD_OPTIONS[@]}" --show-bin-path)"

STAGING_DIR="$(mktemp -d "$BUILD_DIR/package.XXXXXX")"
trap 'rm -rf "$STAGING_DIR"' EXIT
APP_DIR="$STAGING_DIR/MOUSE.app"
mkdir -p "$APP_DIR/Contents/MacOS" "$APP_DIR/Contents/Resources"
cp "$BIN_DIR/MOUSE" "$APP_DIR/Contents/MacOS/MOUSE"
cp "$ROOT_DIR/Resources/Info.plist" "$APP_DIR/Contents/Info.plist"
chmod 755 "$APP_DIR/Contents/MacOS/MOUSE"
printf 'APPL????' > "$APP_DIR/Contents/PkgInfo"

xcrun swift -module-cache-path "$BUILD_DIR/module-cache" \
    "$ROOT_DIR/scripts/make-icon.swift" "$STAGING_DIR/AppIcon.iconset"
cp "$STAGING_DIR/AppIcon.icns" "$APP_DIR/Contents/Resources/AppIcon.icns"

plutil -lint "$APP_DIR/Contents/Info.plist"
codesign --force --sign - --timestamp=none "$APP_DIR"
codesign --verify --strict "$APP_DIR"

# Only replace the application generated by this script; leave other exports.
rm -rf "$ROOT_DIR/dist/MOUSE.app"
mv "$APP_DIR" "$ROOT_DIR/dist/MOUSE.app"
echo "Built: $ROOT_DIR/dist/MOUSE.app"
